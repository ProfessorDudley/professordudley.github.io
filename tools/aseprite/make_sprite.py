"""Test generator for the Aseprite LLM pipeline.

Defines one 16x16 test sprite (gold coin, house palette), then emits:
  1. <name>.lua  - self-contained Aseprite batch script (DATA + paint + save).
                   The user runs:  aseprite -b --script <name>.lua
  2. <name>_preview.png - PIL render of the exact same data (scaled 8x),
                   a proxy for what Aseprite will paint. Aseprite is not
                   installed on this machine, so this validates the data.
"""
import json
import math
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))

PALETTE = {
    "B": "8A5A1E",  # dark amber outline
    "A": "EBA93F",  # amber face
    "P": "F7E3B8",  # pale highlight
    "D": "5C3D12",  # deep shade (inner ring)
}

LUA_TEMPLATE = """-- Generated by make_sprite.py -- do not hand-edit, edit the generator.
-- Run headless:  aseprite -b --script {fname} [--script-param out=DIR]
-- Produces <name>.ase + <name>.gif (all frames).
"""

LUA_SINGLE = LUA_TEMPLATE + """-- DATA
local W, H = {w}, {h}
local PALETTE = {{
{pal_entries}
}}
local ROWS = {{
{rows}
}}

local function hexrgb(h)
  return tonumber(h:sub(1, 2), 16), tonumber(h:sub(3, 4), 16), tonumber(h:sub(5, 6), 16)
end

local function outpath(ext)
  local dir = app.params["out"] or "."
  return dir .. "/{name}." .. ext
end

local sprite = Sprite(W, H)
local cel = sprite:newCel(sprite.layers[1], 1)
local img = cel.image
for y = 0, H - 1 do
  local row = ROWS[y + 1]
  for x = 0, W - 1 do
    local key = row:sub(x + 1, x + 1)
    if key ~= "." then
      local r, g, b = hexrgb(PALETTE[key])
      img:drawPixel(x, y, app.pixelColor.rgba(r, g, b, 255))
    end
  end
end
app.refresh()
sprite:saveCopyAs(outpath("ase"))
sprite:saveCopyAs(outpath("png"))
print("saved " .. outpath("ase") .. " + " .. outpath("png"))
"""

LUA_FRAMES = LUA_TEMPLATE + """-- DATA
local W, H = {w}, {h}
local PALETTE = {{
{pal_entries}
}}
local FRAMES = {{
{frames}
}}

local function hexrgb(h)
  return tonumber(h:sub(1, 2), 16), tonumber(h:sub(3, 4), 16), tonumber(h:sub(5, 6), 16)
end

local function outpath(ext)
  local dir = app.params["out"] or "."
  return dir .. "/{name}." .. ext
end

local function paint(img, rows)
  for y = 0, H - 1 do
    local row = rows[y + 1]
    for x = 0, W - 1 do
      local key = row:sub(x + 1, x + 1)
      if key ~= "." then
        local r, g, b = hexrgb(PALETTE[key])
        img:drawPixel(x, y, app.pixelColor.rgba(r, g, b, 255))
      end
    end
  end
end

local sprite = Sprite(W, H)
for i = 2, #FRAMES do sprite:newFrame() end
for f, rows in ipairs(FRAMES) do
  paint(sprite:newCel(sprite.layers[1], f).image, rows)
end
pcall(function()
  for _, fr in ipairs(sprite.frames) do fr.duration = 0.35 end
end)
app.refresh()
sprite:saveCopyAs(outpath("ase"))
sprite:saveCopyAs(outpath("gif"))
print("saved " .. outpath("ase") .. " + " .. outpath("gif"))
"""


def coin_rows(w=16, h=16):
    rows = []
    cx = cy = (w - 1) / 2
    for y in range(h):
        row = []
        for x in range(w):
            d = math.hypot(x - cx, y - cy)
            if d > 7.2:
                row.append(".")
            elif d > 6.2:
                row.append("B")
            elif abs(d - 3.5) < 0.7:
                row.append("D")
            elif x + y < 13 and d < 5.5:
                row.append("P")
            else:
                row.append("A")
        rows.append("".join(row))
    return rows


def emit(name, rows, palette, scale=8):
    emit_frames(name, [rows], palette, scale=scale, still=True)


def emit_frames(name, frames, palette, scale=8, still=False):
    w = len(frames[0][0])
    h = len(frames[0])
    for rows in frames:
        assert len(rows) == h and all(len(r) == w for r in rows), "ragged rows"
    pal_entries = "\n".join(f'  {k} = "{v}",' for k, v in palette.items())

    if still:
        row_entries = "\n".join(f'  "{r}",' for r in frames[0])
        lua = LUA_SINGLE.format(
            fname=f"{name}.lua", name=name, w=w, h=h,
            pal_entries=pal_entries, rows=row_entries,
        )
    else:
        frame_entries = []
        for rows in frames:
            inner = "\n".join(f'    "{r}",' for r in rows)
            frame_entries.append("  {\n" + inner + "\n  },")
        lua = LUA_FRAMES.format(
            fname=f"{name}.lua", name=name, w=w, h=h,
            pal_entries=pal_entries, frames="\n".join(frame_entries),
        )
    with open(os.path.join(HERE, f"{name}.lua"), "w") as f:
        f.write(lua)

    def render(rows):
        img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        px = img.load()
        for y, row in enumerate(rows):
            for x, key in enumerate(row):
                if key != ".":
                    hx = palette[key]
                    px[x, y] = (int(hx[0:2], 16), int(hx[2:4], 16), int(hx[4:6], 16), 255)
        return img.resize((w * scale, h * scale), Image.NEAREST)

    if still:
        render(frames[0]).save(os.path.join(HERE, f"{name}_preview.png"))
    else:
        imgs = [render(r) for r in frames]
        imgs[0].save(
            os.path.join(HERE, f"{name}_preview.gif"),
            save_all=True, append_images=imgs[1:], duration=350, loop=0,
        )

    with open(os.path.join(HERE, f"{name}.json"), "w") as f:
        json.dump({"w": w, "h": h, "palette": palette, "frames": frames}, f, indent=2)
    print(f"wrote {name}.lua + {name}.json + preview ({w}x{h}, {len(frames)} frame(s))")


HERO_PALETTE = {
    "K": "171214",  # outline
    "H": "F06BA7",  # pink hair
    "h": "A93A6E",  # dark pink shade
    "S": "F2C9A0",  # skin
    "s": "C98F66",  # skin shade
    "E": "241A20",  # eyes
    "J": "2A2A33",  # jacket
    "A": "EBA93F",  # amber shirt (house colour)
}


def hero_rows():
    w, h = 16, 16
    g = [["."] * w for _ in range(h)]

    def rect(x0, y0, x1, y1, c):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                g[y][x] = c

    # body
    rect(3, 10, 12, 15, "K")
    rect(4, 11, 11, 14, "J")
    rect(6, 11, 9, 13, "A")     # shirt front
    rect(3, 14, 3, 14, "S")     # hands
    rect(12, 14, 12, 14, "S")
    rect(4, 15, 7, 15, "h")     # pink boots
    rect(8, 15, 11, 15, "h")
    # hair mass
    rect(2, 1, 13, 10, "K")
    rect(3, 2, 12, 9, "H")
    rect(11, 2, 12, 9, "h")     # shade, light from left
    # face
    rect(5, 4, 10, 8, "S")
    rect(9, 4, 10, 8, "s")
    rect(4, 2, 11, 4, "H")      # fringe
    rect(11, 4, 11, 4, "h")
    # side locks
    rect(3, 4, 4, 10, "H")
    rect(11, 4, 12, 10, "H")
    rect(11, 6, 11, 10, "h")
    # features
    rect(7, 9, 8, 9, "S")       # neck
    rect(5, 6, 5, 6, "E")       # eyes
    rect(10, 6, 10, 6, "E")
    rect(7, 8, 8, 8, "s")       # mouth
    return ["".join(r) for r in g]


def bob(rows):
    return rows[1:] + ["." * len(rows[0])]


if __name__ == "__main__":
    emit("coin", coin_rows(), PALETTE)
    base = hero_rows()
    for r in base:
        print(r)
    emit_frames("hero", [base, bob(base)], HERO_PALETTE)
