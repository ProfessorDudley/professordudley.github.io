"""Test generator for the Aseprite LLM pipeline.

Defines one 16x16 test sprite (gold coin, house palette), then emits:
  1. <name>.lua  - self-contained Aseprite batch script (DATA + paint + save).
                   The user runs:  aseprite -b --script <name>.lua
  2. <name>_preview.png - PIL render of the exact same data (scaled 8x),
                   a proxy for what Aseprite will paint. Aseprite is not
                   installed on this machine, so this validates the data.
"""
import json
import math
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))

PALETTE = {
    "B": "8A5A1E",  # dark amber outline
    "A": "EBA93F",  # amber face
    "P": "F7E3B8",  # pale highlight
    "D": "5C3D12",  # deep shade (inner ring)
}

LUA_TEMPLATE = """-- Generated by make_sprite.py -- do not hand-edit, edit the generator.
-- Run headless:  aseprite -b --script {fname} [--script-param out=DIR]
-- Produces <name>.ase + <name>.png (via saveCopyAs, format from extension).

local W, H = {w}, {h}
local PALETTE = {{
{pal_entries}
}}
local ROWS = {{
{rows}
}}

local function hexrgb(h)
  return tonumber(h:sub(1, 2), 16), tonumber(h:sub(3, 4), 16), tonumber(h:sub(5, 6), 16)
end

local function outpath(ext)
  local dir = app.params["out"] or "."
  return dir .. "/{name}." .. ext
end

local sprite = Sprite(W, H)
local cel = sprite:newCel(sprite.layers[1], 1)
local img = cel.image
for y = 0, H - 1 do
  local row = ROWS[y + 1]
  for x = 0, W - 1 do
    local key = row:sub(x + 1, x + 1)
    if key ~= "." then
      local r, g, b = hexrgb(PALETTE[key])
      img:drawPixel(x, y, app.pixelColor.rgba(r, g, b, 255))
    end
  end
end
app.refresh()
sprite:saveCopyAs(outpath("ase"))
sprite:saveCopyAs(outpath("png"))
print("saved " .. outpath("ase") .. " + " .. outpath("png"))
"""


def coin_rows(w=16, h=16):
    rows = []
    cx = cy = (w - 1) / 2
    for y in range(h):
        row = []
        for x in range(w):
            d = math.hypot(x - cx, y - cy)
            if d > 7.2:
                row.append(".")
            elif d > 6.2:
                row.append("B")
            elif abs(d - 3.5) < 0.7:
                row.append("D")
            elif x + y < 13 and d < 5.5:
                row.append("P")
            else:
                row.append("A")
        rows.append("".join(row))
    return rows


def emit(name, rows, palette, scale=8):
    w, h = len(rows[0]), len(rows)
    assert all(len(r) == w for r in rows), "ragged rows"
    pal_entries = "\n".join(f'  {k} = "{v}",' for k, v in palette.items())
    row_entries = "\n".join(f'  "{r}",' for r in rows)
    lua = LUA_TEMPLATE.format(
        fname=f"{name}.lua", name=name, w=w, h=h,
        pal_entries=pal_entries, rows=row_entries,
    )
    with open(os.path.join(HERE, f"{name}.lua"), "w") as f:
        f.write(lua)

    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    px = img.load()
    for y, row in enumerate(rows):
        for x, key in enumerate(row):
            if key != ".":
                hx = palette[key]
                px[x, y] = (int(hx[0:2], 16), int(hx[2:4], 16), int(hx[4:6], 16), 255)
    img = img.resize((w * scale, h * scale), Image.NEAREST)
    img.save(os.path.join(HERE, f"{name}_preview.png"))

    with open(os.path.join(HERE, f"{name}.json"), "w") as f:
        json.dump({"w": w, "h": h, "palette": palette, "rows": rows}, f, indent=2)
    print(f"wrote {name}.lua + {name}.json + {name}_preview.png ({w}x{h})")


if __name__ == "__main__":
    emit("coin", coin_rows(), PALETTE)
